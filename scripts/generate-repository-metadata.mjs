import fs from "node:fs";
import path from "node:path";

const migrationDirectory = path.join(process.cwd(), "supabase", "migrations");
const outputPath = path.join(
  process.cwd(),
  "src",
  "generated",
  "repositoryMetadata.ts",
);
const migrations = fs
  .readdirSync(migrationDirectory)
  .filter((name) => /^\d{14}_.+\.sql$/.test(name))
  .sort();
if (!migrations.length) throw new Error("No repository migrations were found.");
const head = migrations.at(-1).slice(0, 14);
const output = `// Generated by scripts/generate-repository-metadata.mjs.\n// Do not edit this value independently of the migration inventory.\nexport const REPOSITORY_MIGRATION_HEAD = "${head}" as const;\n`;

if (process.argv.includes("--check")) {
  const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, "utf8") : "";
  if (current !== output) {
    throw new Error(
      `Repository metadata is stale. Run npm run generate:repository-metadata (expected ${head}).`,
    );
  }
  console.log(`Repository metadata matches migration head ${head}.`);
} else {
  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, output);
  console.log(`Generated repository metadata for migration head ${head}.`);
}
