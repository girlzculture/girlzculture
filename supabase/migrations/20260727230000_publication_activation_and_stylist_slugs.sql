-- Keep automatic reconciliation idempotent. Active pilot salons do not churn
-- through Needs Attention while the exact recorded override remains effective;
-- newly introduced, non-overridden required gates still remove eligibility.
create or replace function public.reconcile_salon_publication(
  p_salon_id uuid,
  p_actor_id uuid default null,
  p_reason text default 'Eligibility recalculated'
)
returns jsonb
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  v_before public.salons%rowtype;
  v_after public.salons%rowtype;
  v_diagnostic jsonb;
  v_approved boolean;
  v_override_effective boolean;
  v_application_active boolean;
  v_future_count integer;
begin
  select *
  into v_before
  from public.salons
  where id = p_salon_id
  for update;
  if not found then
    raise exception 'Salon not found.';
  end if;

  select
    v_before.approved_at is not null
    or exists (
      select 1
      from public.salon_applications application
      where application.salon_id = p_salon_id
        and application.status in ('Approved', 'Active')
    )
  into v_approved;

  if v_approved
     and nullif(trim(coalesce(v_before.name, '')), '') is not null
     and v_before.name <> 'Pending salon application'
     and (
       v_before.slug is null
       or v_before.slug ~ '^pending-'
     ) then
    update public.salons
    set slug = public.generate_unique_salon_slug(id, name)
    where id = p_salon_id;
  end if;

  v_diagnostic := public.salon_publication_diagnostic(p_salon_id);
  v_override_effective :=
    coalesce((v_diagnostic ->> 'override_active')::boolean, false)
    and coalesce(
      (v_diagnostic ->> 'all_required_complete')::boolean,
      false
    );

  if not (
    v_before.status = 'Active'
    and v_override_effective
  ) then
    perform public.reconcile_salon_lifecycle(
      p_salon_id,
      p_actor_id,
      p_reason
    );
  end if;

  v_diagnostic := public.salon_publication_diagnostic(p_salon_id);
  select exists (
    select 1
    from public.salon_applications application
    where application.salon_id = p_salon_id
      and application.status = 'Active'
  )
  into v_application_active;

  select *
  into v_after
  from public.salons
  where id = p_salon_id
  for update;

  if coalesce((v_diagnostic ->> 'all_required_complete')::boolean, false)
     and coalesce((v_diagnostic ->> 'override_active')::boolean, false)
     and (v_before.status = 'Active' or v_application_active)
     and v_after.status not in ('Suspended', 'Offboarded')
     and v_after.owner_unpublished_at is null then
    if v_after.status is distinct from 'Active' then
      select count(*)::integer
      into v_future_count
      from public.bookings booking
      where booking.salon_id = p_salon_id
        and booking.appointment_datetime >= now()
        and lower(coalesce(booking.status, ''))
          not in ('cancelled', 'canceled', 'completed');

      insert into public.salon_status_audit(
        salon_id,
        previous_status,
        new_status,
        reason,
        acting_admin_id,
        future_booking_count,
        actor_type,
        source
      ) values (
        p_salon_id,
        v_after.status,
        'Active',
        'Authorized pilot publication override remains effective',
        p_actor_id,
        v_future_count,
        case when p_actor_id is null then 'engine' else 'admin' end,
        'pilot_publication_override'
      );
    end if;

    update public.salons
    set status = 'Active',
        is_discoverable = true,
        activated_at = coalesce(activated_at, now()),
        lifecycle_reason = 'Authorized pilot publication override'
    where id = p_salon_id;
  elsif not coalesce(
    (v_diagnostic ->> 'all_required_complete')::boolean,
    false
  ) then
    update public.salons
    set is_discoverable = false
    where id = p_salon_id;
  else
    update public.salons
    set is_discoverable =
      is_discoverable
      and owner_unpublished_at is null
      and status = 'Active'
      and slug is not null
      and slug !~ '^pending-'
    where id = p_salon_id;
  end if;

  return public.salon_publication_diagnostic(p_salon_id);
end;
$$;

create or replace function public.admin_set_salon_publication_override(
  p_application_id uuid,
  p_actor_id uuid,
  p_enabled boolean,
  p_reason text
)
returns jsonb
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  v_application public.salon_applications%rowtype;
  v_override public.salon_publication_overrides%rowtype;
  v_diagnostic jsonb;
  v_gates jsonb;
  v_changed boolean := false;
  v_action text;
  v_reason text;
begin
  if not exists (
    select 1
    from public.admin_users admin_user
    where coalesce(admin_user.user_id, admin_user.id) = p_actor_id
      and admin_user.status = 'Active'
      and (
        coalesce(admin_user.is_super_admin, false)
        or coalesce(
          (
            admin_user.permissions
            ->> 'pilot_activation_override'
          )::boolean,
          false
        )
      )
  ) then
    raise exception 'Forbidden' using errcode = '42501';
  end if;

  v_reason := trim(coalesce(p_reason, ''));
  if length(v_reason) < 12 then
    raise exception 'Enter an override reason of at least 12 characters.'
      using errcode = '22023';
  end if;

  select *
  into v_application
  from public.salon_applications
  where id = p_application_id
  for update;
  if not found then
    raise exception 'Application not found.' using errcode = 'P0002';
  end if;
  if v_application.status not in ('Approved', 'Active') then
    raise exception 'This salon application must be approved first.'
      using errcode = '22023';
  end if;

  perform 1
  from public.salons
  where id = v_application.salon_id
  for update;
  if not found then
    raise exception 'Salon not found.' using errcode = 'P0002';
  end if;

  v_diagnostic :=
    public.salon_publication_diagnostic(v_application.salon_id);
  v_gates := coalesce(
    v_diagnostic -> 'missing_gate_keys',
    '[]'::jsonb
  );

  select *
  into v_override
  from public.salon_publication_overrides publication_override
  where publication_override.salon_id = v_application.salon_id
  for update;

  if p_enabled then
    if jsonb_array_length(v_gates) = 0 then
      return jsonb_build_object(
        'changed', false,
        'active', false,
        'reason', 'No incomplete gate needs an override.',
        'lifecycle', v_diagnostic
      );
    end if;

    if v_override.id is null then
      insert into public.salon_publication_overrides(
        salon_id,
        application_id,
        is_active,
        reason,
        overridden_gates,
        gate_snapshot,
        granted_by,
        granted_at,
        revoked_by,
        revoked_at,
        updated_at
      ) values (
        v_application.salon_id,
        v_application.id,
        true,
        v_reason,
        v_gates,
        coalesce(v_diagnostic -> 'checks', '{}'::jsonb),
        p_actor_id,
        now(),
        null,
        null,
        now()
      )
      returning * into v_override;
      v_changed := true;
      v_action := 'Granted';
    elsif not v_override.is_active
       or v_override.reason is distinct from v_reason
       or v_override.overridden_gates is distinct from v_gates
       or v_override.application_id is distinct from v_application.id then
      update public.salon_publication_overrides
      set application_id = v_application.id,
          is_active = true,
          reason = v_reason,
          overridden_gates = v_gates,
          gate_snapshot = coalesce(
            v_diagnostic -> 'checks',
            '{}'::jsonb
          ),
          granted_by = p_actor_id,
          granted_at = now(),
          revoked_by = null,
          revoked_at = null,
          updated_at = now()
      where id = v_override.id
      returning * into v_override;
      v_changed := true;
      v_action := 'Updated';
    end if;
  elsif v_override.id is not null and v_override.is_active then
    update public.salon_publication_overrides
    set is_active = false,
        reason = v_reason,
        revoked_by = p_actor_id,
        revoked_at = now(),
        updated_at = now()
    where id = v_override.id
    returning * into v_override;
    v_changed := true;
    v_action := 'Revoked';
  end if;

  if v_changed then
    insert into public.salon_publication_override_audit(
      override_id,
      salon_id,
      application_id,
      action,
      reason,
      overridden_gates,
      gate_snapshot,
      acting_admin_id
    ) values (
      v_override.id,
      v_application.salon_id,
      v_application.id,
      v_action,
      v_reason,
      v_override.overridden_gates,
      v_override.gate_snapshot,
      p_actor_id
    );
  end if;

  v_diagnostic := public.reconcile_salon_publication(
    v_application.salon_id,
    p_actor_id,
    case
      when p_enabled then 'Authorized pilot publication override reviewed'
      else 'Authorized pilot publication override revoked'
    end
  );

  return jsonb_build_object(
    'changed', v_changed,
    'active', coalesce(v_override.is_active, false),
    'override_id', v_override.id,
    'overridden_gates',
      coalesce(v_override.overridden_gates, '[]'::jsonb),
    'lifecycle', v_diagnostic
  );
end;
$$;

create or replace function public.admin_activate_salon_application(
  p_application_id uuid,
  p_actor_id uuid,
  p_use_pilot_override boolean default false,
  p_reason text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  v_application public.salon_applications%rowtype;
  v_salon public.salons%rowtype;
  v_current public.salons%rowtype;
  v_diagnostic jsonb;
  v_override_result jsonb;
  v_override_changed boolean := false;
  v_changed boolean := false;
  v_future_count integer := 0;
begin
  if not exists (
    select 1
    from public.admin_users admin_user
    where coalesce(admin_user.user_id, admin_user.id) = p_actor_id
      and admin_user.status = 'Active'
      and (
        coalesce(admin_user.is_super_admin, false)
        or coalesce(
          (admin_user.permissions ->> 'submissions')::boolean,
          false
        )
      )
  ) then
    raise exception 'Forbidden' using errcode = '42501';
  end if;

  select *
  into v_application
  from public.salon_applications
  where id = p_application_id
  for update;
  if not found then
    raise exception 'Application not found.' using errcode = 'P0002';
  end if;

  select *
  into v_salon
  from public.salons
  where id = v_application.salon_id
  for update;
  if not found then
    raise exception 'Salon not found.' using errcode = 'P0002';
  end if;

  if v_application.status not in ('Approved', 'Active') then
    return jsonb_build_object(
      'ok', false,
      'changed', false,
      'code', 'APPLICATION_NOT_APPROVED',
      'message', 'This salon application must be approved before publication.'
    );
  end if;

  perform public.reconcile_salon_publication(
    v_application.salon_id,
    p_actor_id,
    'Authorized admin publication check'
  );

  if p_use_pilot_override then
    v_override_result := public.admin_set_salon_publication_override(
      v_application.id,
      p_actor_id,
      true,
      p_reason
    );
    v_override_changed := coalesce(
      (v_override_result ->> 'changed')::boolean,
      false
    );
  end if;

  v_diagnostic := public.reconcile_salon_publication(
    v_application.salon_id,
    p_actor_id,
    case
      when p_use_pilot_override
        then 'Authorized pilot publication activation'
      else 'Authorized admin publication activation'
    end
  );

  if not coalesce(
    (v_diagnostic ->> 'all_required_complete')::boolean,
    false
  ) then
    return jsonb_build_object(
      'ok', false,
      'changed', v_override_changed,
      'code', 'PUBLICATION_GATES_INCOMPLETE',
      'message', 'This salon still has incomplete publication requirements.',
      'missing', coalesce(
        v_diagnostic -> 'effective_missing_gate_labels',
        '[]'::jsonb
      ),
      'lifecycle', v_diagnostic
    );
  end if;

  select *
  into v_current
  from public.salons
  where id = v_application.salon_id
  for update;

  if v_current.status in ('Suspended', 'Offboarded', 'New', 'Pending')
     or v_current.owner_unpublished_at is not null then
    return jsonb_build_object(
      'ok', false,
      'changed', v_override_changed,
      'code', 'SALON_STATE_BLOCKS_PUBLICATION',
      'message', 'This salon state does not allow public activation.',
      'missing', '[]'::jsonb,
      'lifecycle', v_diagnostic
    );
  end if;

  if v_current.status is distinct from 'Active' then
    select count(*)::integer
    into v_future_count
    from public.bookings booking
    where booking.salon_id = v_application.salon_id
      and booking.appointment_datetime >= now()
      and lower(coalesce(booking.status, ''))
        not in ('cancelled', 'canceled', 'completed');

    insert into public.salon_status_audit(
      salon_id,
      previous_status,
      new_status,
      reason,
      acting_admin_id,
      future_booking_count,
      actor_type,
      source
    ) values (
      v_application.salon_id,
      v_current.status,
      'Active',
      case
        when p_use_pilot_override
          then 'Authorized pilot publication override'
        else 'Every required publication gate passed'
      end,
      p_actor_id,
      v_future_count,
      'admin',
      case
        when p_use_pilot_override
          then 'pilot_publication_override'
        else 'admin_submissions'
      end
    );
    v_changed := true;
  end if;

  update public.salons
  set status = 'Active',
      is_discoverable = true,
      approved_at = coalesce(approved_at, now()),
      activated_at = coalesce(activated_at, now()),
      lifecycle_reason = case
        when p_use_pilot_override
          then 'Authorized pilot publication override'
        else null
      end
  where id = v_application.salon_id;

  if v_application.status is distinct from 'Active' then
    update public.salon_applications
    set status = 'Active',
        reviewed_by = p_actor_id,
        reviewed_at = coalesce(reviewed_at, now()),
        rejection_reason = null
    where id = v_application.id;
    v_changed := true;
  end if;

  v_changed := v_changed or v_override_changed;
  v_diagnostic :=
    public.salon_publication_diagnostic(v_application.salon_id);

  return jsonb_build_object(
    'ok', true,
    'changed', v_changed,
    'idempotent', not v_changed,
    'application_id', v_application.id,
    'salon_id', v_application.salon_id,
    'application_status', 'Active',
    'override_active',
      coalesce((v_diagnostic ->> 'override_active')::boolean, false),
    'overridden_gates',
      coalesce(v_diagnostic -> 'overridden_gates', '[]'::jsonb),
    'lifecycle', v_diagnostic
  );
end;
$$;

