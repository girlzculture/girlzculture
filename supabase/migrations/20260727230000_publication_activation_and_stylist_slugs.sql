-- Final pilot publication correction:
--   * one config-aware publication diagnostic governs lifecycle, profile RLS,
--     discovery, and explicit admin activation;
--   * public profile visibility is distinct from current booking availability;
--   * pilot overrides are explicit, authorized, idempotent, and immutably
--     audited without creating or changing any financial record;
--   * stylist profile URLs use stable, collision-safe slugs.
begin;

alter table public.stylists
  add column if not exists slug text;

create or replace function public.stylist_slugify(value text)
returns text
language sql
immutable
parallel safe
set search_path = public
as $$
  select trim(
    both '-'
    from regexp_replace(
      regexp_replace(lower(coalesce(value, '')), '[^a-z0-9]+', '-', 'g'),
      '-+',
      '-',
      'g'
    )
  );
$$;

create or replace function public.generate_unique_stylist_slug(
  p_salon_id uuid,
  p_stylist_id uuid,
  p_name text
)
returns text
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_base text;
  v_candidate text;
  v_suffix integer := 1;
begin
  v_base := left(nullif(public.stylist_slugify(p_name), ''), 72);
  if v_base is null then
    v_base := 'stylist';
  end if;
  v_candidate := v_base;

  while exists (
    select 1
    from public.stylists stylist
    where stylist.salon_id = p_salon_id
      and stylist.id is distinct from p_stylist_id
      and stylist.slug = v_candidate
  ) loop
    v_suffix := v_suffix + 1;
    v_candidate := left(v_base, greatest(1, 72 - length(v_suffix::text) - 1))
      || '-' || v_suffix::text;
  end loop;

  return v_candidate;
end;
$$;

do $$
declare
  v_stylist record;
begin
  for v_stylist in
    select id, salon_id, name
    from public.stylists
    where nullif(trim(coalesce(slug, '')), '') is null
    order by salon_id, created_at, id
  loop
    perform pg_advisory_xact_lock(
      hashtextextended('stylist-slug:' || v_stylist.salon_id::text, 0)
    );
    update public.stylists
    set slug = public.generate_unique_stylist_slug(
      v_stylist.salon_id,
      v_stylist.id,
      v_stylist.name
    )
    where id = v_stylist.id;
  end loop;
end
$$;

