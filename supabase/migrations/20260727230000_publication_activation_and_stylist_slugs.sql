create or replace function public.assign_stable_stylist_slug()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'UPDATE' and new.slug is distinct from old.slug then
    raise exception 'Published stylist URLs are stable and cannot be changed.'
      using errcode = '22023';
  end if;

  -- The public identifier is always generated by the database. Ignoring a
  -- caller-supplied INSERT value prevents malformed or path-like slugs from
  -- bypassing the canonical URL contract through a direct API insert.
  if tg_op = 'INSERT' then
    perform pg_advisory_xact_lock(
      hashtextextended('stylist-slug:' || new.salon_id::text, 0)
    );
    new.slug := public.generate_unique_stylist_slug(
      new.salon_id,
      new.id,
      new.name
    );
  end if;
  return new;
end;
$$;

