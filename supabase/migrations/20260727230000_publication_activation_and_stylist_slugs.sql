-- The publication diagnostic is authoritative. It uses the configurable
-- lifecycle gates, corrects subscription truth from the subscriptions table,
-- adds the public-slug gate, and then applies only the exact gates recorded by
-- an active pilot override. Raw and effective completion remain separately
-- visible so an override can never masquerade as a completed requirement.
create or replace function public.salon_publication_diagnostic(p_salon_id uuid)
returns jsonb
language plpgsql
stable
security definer
set search_path = public, auth
as $$
declare
  v_base jsonb;
  v_salon public.salons%rowtype;
  v_override public.salon_publication_overrides%rowtype;
  v_checks jsonb;
  v_key text;
  v_check jsonb;
  v_required boolean;
  v_passed boolean;
  v_overridden boolean;
  v_required_count integer := 0;
  v_passed_count integer := 0;
  v_effective_passed_count integer := 0;
  v_raw_complete boolean := true;
  v_effective_complete boolean := true;
  v_raw_missing_keys jsonb := '[]'::jsonb;
  v_raw_missing_labels jsonb := '[]'::jsonb;
  v_effective_missing_keys jsonb := '[]'::jsonb;
  v_effective_missing_labels jsonb := '[]'::jsonb;
  v_slug_ready boolean;
  v_profile_public boolean;
  v_discovery_eligible boolean;
  v_closed_today boolean;
begin
  select *
  into v_salon
  from public.salons
  where id = p_salon_id;
  if not found then
    raise exception 'Salon not found.';
  end if;

  select *
  into v_override
  from public.salon_publication_overrides publication_override
  where publication_override.salon_id = p_salon_id
    and publication_override.is_active = true;

  v_base := public.salon_lifecycle_diagnostic(p_salon_id);
  v_slug_ready :=
    nullif(trim(coalesce(v_salon.slug, '')), '') is not null
    and v_salon.slug !~ '^pending-';

  v_checks := coalesce(v_base -> 'checks', '{}'::jsonb)
    || jsonb_build_object(
      'public_slug',
      jsonb_build_object(
        'label', 'Public salon URL',
        'required', true,
        'passed', v_slug_ready,
        'action', '/salon/dashboard/my-page'
      )
    );

  -- The authoritative subscription relation, not its asynchronous mirror,
  -- controls publication.
  if v_checks ? 'active_subscription' then
    v_checks := jsonb_set(
      v_checks,
      '{active_subscription,passed}',
      to_jsonb(public.has_active_subscription(p_salon_id)),
      true
    );
  end if;

  for v_key, v_check in
    select item.key, item.value
    from jsonb_each(v_checks) item
  loop
    v_required := coalesce((v_check ->> 'required')::boolean, false);
    v_passed := coalesce((v_check ->> 'passed')::boolean, false);
    v_overridden :=
      v_required
      and not v_passed
      and v_override.id is not null
      and v_override.overridden_gates ? v_key;

    v_checks := jsonb_set(
      v_checks,
      array[v_key],
      v_check || jsonb_build_object(
        'overridden', v_overridden,
        'effective_passed', v_passed or v_overridden
      ),
      true
    );

    if v_required then
      v_required_count := v_required_count + 1;
      if v_passed then
        v_passed_count := v_passed_count + 1;
      else
        v_raw_complete := false;
        v_raw_missing_keys := v_raw_missing_keys || jsonb_build_array(v_key);
        v_raw_missing_labels := v_raw_missing_labels
          || jsonb_build_array(coalesce(v_check ->> 'label', v_key));
      end if;

      if v_passed or v_overridden then
        v_effective_passed_count := v_effective_passed_count + 1;
      else
        v_effective_complete := false;
        v_effective_missing_keys :=
          v_effective_missing_keys || jsonb_build_array(v_key);
        v_effective_missing_labels :=
          v_effective_missing_labels
          || jsonb_build_array(coalesce(v_check ->> 'label', v_key));
      end if;
    end if;
  end loop;

  v_profile_public :=
    v_effective_complete
    and v_salon.status = 'Active'
    and v_salon.is_discoverable = true
    and v_salon.owner_unpublished_at is null;
  v_closed_today :=
    coalesce(v_salon.is_closed_override, false) = true
    and v_salon.closed_override_date = (
      now() at time zone coalesce(
        nullif(v_salon.time_zone, ''),
        'America/New_York'
      )
    )::date;
  v_discovery_eligible :=
    v_profile_public
    and coalesce(v_salon.accepting_bookings, true) = true
    and not v_closed_today;

  return v_base || jsonb_build_object(
    'checks', v_checks,
    'valid_public_slug', v_slug_ready,
    'actual_required_complete', v_raw_complete,
    'all_required_complete', v_effective_complete,
    'required_count', v_required_count,
    'passed_count', v_passed_count,
    'effective_passed_count', v_effective_passed_count,
    'progress',
      case
        when v_required_count = 0 then 100
        else round(
          (v_passed_count::numeric / v_required_count::numeric) * 100
        )::integer
      end,
    'missing_gate_keys', v_raw_missing_keys,
    'missing_gate_labels', v_raw_missing_labels,
    'effective_missing_gate_keys', v_effective_missing_keys,
    'effective_missing_gate_labels', v_effective_missing_labels,
    'override_active', v_override.id is not null,
    'override_id', v_override.id,
    'overridden_gates',
      coalesce(v_override.overridden_gates, '[]'::jsonb),
    'override_reason', v_override.reason,
    'public_eligible',
      v_effective_complete
      and v_salon.status not in ('Suspended', 'Offboarded', 'New', 'Pending')
      and v_salon.owner_unpublished_at is null,
    'profile_public', v_profile_public,
    'discovery_eligible', v_discovery_eligible,
    'application_state',
      case
        when coalesce(
          (v_checks #>> '{application_approved,effective_passed}')::boolean,
          false
        ) then 'Approved'
        else 'Awaiting approval'
      end,
    'setup_state',
      case
        when v_raw_complete then 'Complete'
        when v_override.id is not null and v_effective_complete
          then 'Pilot override'
        else 'Needs setup'
      end,
    'subscription_state',
      case
        when public.has_active_subscription(p_salon_id) then 'active'
        else 'inactive'
      end,
    'address_state',
      case
        when v_salon.geocode_status = 'success'
          and not v_salon.address_needs_review then 'Ready'
        else 'Needs review'
      end,
    'marketplace_state', v_salon.status,
    'publication_state',
      case
        when v_salon.status = 'Suspended' then 'Suspended'
        when v_salon.status = 'Offboarded' then 'Offboarded'
        when v_salon.owner_unpublished_at is not null then 'Owner unpublished'
        when v_profile_public then 'Published'
        when v_override.id is not null and not v_effective_complete
          then 'Override needs review'
        else 'Not published'
      end,
    'accepting_bookings', v_salon.accepting_bookings,
    'closed_today', v_closed_today,
    'owner_unpublished_at', v_salon.owner_unpublished_at,
    'owner_unpublished_reason', v_salon.owner_unpublished_reason,
    'closure_requested_at', v_salon.closure_requested_at
  );
end;
$$;

