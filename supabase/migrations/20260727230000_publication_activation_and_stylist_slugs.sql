-- Profile content remains readable while a published salon temporarily pauses
-- bookings. Availability and organic discovery still use the stricter
-- is_marketplace_visible predicate.
drop policy if exists salons_public_read on public.salons;
create policy salons_public_read
on public.salons for select to anon, authenticated
using (
  public.is_salon_profile_public(id)
  or public.salon_has_permission(id, 'my_page')
  or public.is_admin()
);

drop policy if exists styles_public_read on public.styles;
create policy styles_public_read
on public.styles for select to anon, authenticated
using (
  (
    not is_draft
    and archived_at is null
    and public.is_salon_profile_public(salon_id)
  )
  or public.salon_has_permission(salon_id, 'styles')
  or public.admin_has_permission('salons')
);

