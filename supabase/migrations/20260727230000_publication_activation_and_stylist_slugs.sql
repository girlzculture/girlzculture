create policy stylists_public_read
on public.stylists for select to anon, authenticated
using (
  (
    is_active
    and not is_draft
    and archived_at is null
    and public.is_salon_profile_public(salon_id)
  )
  or public.salon_has_permission(salon_id, 'stylists')
  or public.admin_has_permission('salons')
);

